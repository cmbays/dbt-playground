# Note: N1 set would be even larger, contains ~1000+ kanji
# For efficiency, we'll mark anything not in N5-N2 as "N3" or research manually

def load_extracted_kanji():
    """Load the extracted kanji data"""
    with open('temp/extracted_kanji_raw.json', 'r', encoding='utf-8') as f:
        return json.load(f)

def assign_jlpt_level(character):
    """Assign JLPT level to a kanji character"""
    if character in JLPT_N5:
        return 'N5'
    elif character in JLPT_N4:
        return 'N4'
    elif character in JLPT_N3:
        return 'N3'
    elif character in JLPT_N2:
        return 'N2'
    else:
        # Default to N3 for common kanji, or "NEEDS_RESEARCH" for rare ones
        return 'NEEDS_RESEARCH'

def main():
    print("Assigning JLPT levels to extracted kanji...\n")

    kanji_data = load_extracted_kanji()

    # Statistics
    stats = {'N5': 0, 'N4': 0, 'N3': 0, 'N2': 0, 'N1': 0, 'NEEDS_RESEARCH': 0}
    needs_research = []

    # Assign levels
    for char, data in kanji_data.items():
        level = assign_jlpt_level(char)
        data['jlpt'] = level
        stats[level] += 1

        if level == 'NEEDS_RESEARCH':
            needs_research.append(char)

    # Save updated data
    output_file = 'temp/kanji_with_jlpt.json'
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(kanji_data, f, ensure_ascii=False, indent=2)

    print(f"✅ JLPT levels assigned!")
    print(f"💾 Saved to: {output_file}\n")

    print("📊 JLPT Distribution:")
    print(f"   N5: {stats['N5']} kanji")
    print(f"   N4: {stats['N4']} kanji")
    print(f"   N3: {stats['N3']} kanji")
    print(f"   N2: {stats['N2']} kanji")
    print(f"   N1: {stats['N1']} kanji")
    print(f"   Needs Research: {stats['NEEDS_RESEARCH']} kanji\n")

    if needs_research:
        print(f"⚠️  Kanji needing manual research ({len(needs_research)}):")
        print("   " + ', '.join(needs_research[:20]))
        if len(needs_research) > 20:
            print(f"   ... and {len(needs_research) - 20} more")

        # Save list for reference
        with open('temp/needs_research.txt', 'w', encoding='utf-8') as f:
            f.write('\n'.join(needs_research))
        print("\n📝 Full list saved to: temp/needs_research.txt")

    print("\n✨ Next step: Research uncertain kanji and update levels")

if __name__ == '__main__':
    main()
